def write_text(path: Path, content: str, overwrite: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not overwrite:
        return
    path.write_text(content, encoding="utf-8")


def backup_file(path: Path) -> Path:
    ts = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = path.with_suffix(path.suffix + f".bak_{ts}")
    backup.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    return backup


def try_patch_engine(engine_path: Path, import_line: str, hook_snippet: str) -> Tuple[bool, str]:
    """
    매우 보수적인 자동 패치:
    - import 삽입: 최상단 import 블록 근처(첫 def/class 전)
    - hook 삽입: 'return ...weights...' 형태를 찾으면 직전에 weights = apply_overlays(...)
    실패하면 False + 메시지 반환
    """
    src = engine_path.read_text(encoding="utf-8").splitlines(True)

    # 1) import 삽입 위치: 첫 def/class 직전, 또는 마지막 import 라인 다음
    first_def_idx = None
    last_import_idx = None
    for i, line in enumerate(src):
        if re.match(r"^\s*(def|class)\s+", line):
            first_def_idx = i
            break
        if re.match(r"^\s*(import|from)\s+", line):
            last_import_idx = i

    insert_import_at = None
    if last_import_idx is not None:
        insert_import_at = last_import_idx + 1
    elif first_def_idx is not None:
        insert_import_at = first_def_idx
    else:
        insert_import_at = 0

    # 이미 import가 있으면 중복 삽입 금지
    if any(import_line.strip() in l for l in src):
        imported = True
    else:
        imported = False
        src.insert(insert_import_at, import_line + "\n")

    # 2) hook 삽입: return weights 패턴 탐색
    #    (너무 공격적으로 여러 곳을 바꾸지 않기 위해 "첫 번째 적합 지점 1회만" 적용)
    return_idx = None
    return_var = None
    for i, line in enumerate(src):
        m = re.search(r"return\s+([A-Za-z_][A-Za-z0-9_]*)", line)
        if not m:
            continue
        var = m.group(1)
        if "weight" in var.lower():
            return_idx = i
            return_var = var
            break

    if return_idx is None or return_var is None:
        msg = "엔진에서 'return <...weights...>' 패턴을 못 찾음(자동 패치 보류). patches/ 스니펫을 수동으로 적용하세요."
        return (False, msg)

    # hook line 생성 (returns_history/vix/current_return/timestamp 변수명은 엔진에 따라 다를 수 있음)
    hook_lines = []
    hook_lines.append("\n    # === P0 OVERLAY HOOK (auto) ===\n")
    hook_lines.append(
        f"    {return_var}, _p0_dbg = apply_p0_overlays(\n"
        f"        {return_var},\n"
        f"        returns_history=locals().get('returns_history'),\n"
        f"        vix=locals().get('vix'),\n"
        f"        current_return=locals().get('current_return'),\n"
        f"        timestamp=locals().get('timestamp') or locals().get('date') or None,\n"
        f"    )\n"
    )
    hook_lines.append("    # ==============================\n\n")

    # return 직전에 삽입(들여쓰기 맞춤은 'return' 라인 들여쓰기 기준으로)
    indent = re.match(r"^(\s*)", src[return_idx]).group(1)
    hook_lines = [indent + hl if hl.strip() else hl for hl in hook_lines]
    src[return_idx:return_idx] = hook_lines

    # helper 함수가 이미 있으면 스킵
    if "def apply_p0_overlays(" not in "".join(src):
        src.append("\n\n" + hook_snippet + "\n")

    engine_path.write_text("".join(src), encoding="utf-8")
    return (True, f"자동 패치 성공(import inserted={not imported}, hook at line={return_idx}).")


